// Optic: the window onto a world of text.
//
// A world is a directory. Inside it, docs/ holds the living
// documents - plain text, the whole substance of the system -
// and chain.jsonl is the phylogeny: an append-only, hash-chained
// record of everything the world has done, written in the same
// shape as idem's edition log. proposals/ holds proposed texts
// by their hash: mutations that have been offered to the world
// and not yet kept. Nothing about a world is hidden in a binary.
// Read the directory and you have read the system.
//
// The window's verbs:
//
//   optic seed <world>              found a world with one document
//   optic view <world> [doc]        see the world, or one document
//   optic update <world> <doc>      mold a document directly (stdin)
//   optic propose <world> <doc>     offer a mutation (stdin), unkept
//   optic mutate <world> <doc>      the world offers its own mutation
//   optic proposals <world>         what stands proposed, unresolved
//   optic keep <world> <seq>        the owner keeps a proposal
//   optic discard <world> <seq>     the owner discards a proposal
//   optic log <world>               the phylogeny, verified
//   optic compose <world>           a picture composed from the text
//   optic graft <world> <other>     another world offers its documents
//
// Evolution here is directed. A mutation - written by the owner,
// generated by the world itself, or grafted from another island -
// enters as a proposal in the chain, visible and hash-committed,
// and changes nothing until the owner keeps it. Discards stay in
// the chain too: the fossil record is part of the phylogeny.
//
// Every view verifies before it shows: the chain must hash
// unbroken from GENESIS, and every document's current bytes must
// answer to the hash its latest kept edit committed. A world
// touched outside the window does not render - it reports.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::exit;

fn fail(msg: &str) -> ! {
    eprintln!("optic: {msg}");
    exit(1);
}

fn sha256_hex(bytes: &[u8]) -> String {
    let mut h = Sha256::new();
    h.update(bytes);
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

fn short(hash: &str) -> String {
    hash.chars().take(10).collect()
}

fn default_kind() -> String {
    "edit".to_string()
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct Edit {
    seq: u64,
    #[serde(default = "default_kind")]
    kind: String,
    doc: String,
    before: Option<String>,
    after: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    ref_seq: Option<u64>,
    prev: String,
    hash: String,
}

// v0 chains carry no kind or ref_seq; their entry bodies were
// hashed without those fields. A chain is legacy if its first
// entry predates them, and it verifies under its own body shape
// forever - a world's history is never re-hashed under new rules.
fn entry_body(e: &Edit, legacy: bool) -> String {
    if legacy {
        format!(
            "{}|{}|{}|{}|{}",
            e.seq,
            e.doc,
            e.before.as_deref().unwrap_or("-"),
            e.after,
            e.prev
        )
    } else {
        format!(
            "{}|{}|{}|{}|{}|{}|{}",
            e.seq,
            e.kind,
            e.doc,
            e.before.as_deref().unwrap_or("-"),
            e.after,
            e.ref_seq.map(|r| r.to_string()).unwrap_or_else(|| "-".into()),
            e.prev
        )
    }
}

fn chain_path(world: &Path) -> PathBuf {
    world.join("chain.jsonl")
}

fn docs_dir(world: &Path) -> PathBuf {
    world.join("docs")
}

fn proposals_dir(world: &Path) -> PathBuf {
    world.join("proposals")
}

fn read_chain(world: &Path) -> Vec<Edit> {
    let text = std::fs::read_to_string(chain_path(world))
        .unwrap_or_else(|_| fail("no chain.jsonl here - is this a world? seed one first"));
    let lines: Vec<&str> = text.lines().filter(|l| !l.trim().is_empty()).collect();
    let legacy = lines.first().map(|l| !l.contains("\"kind\"")).unwrap_or(false);
    let mut edits = Vec::new();
    let mut prev = "GENESIS".to_string();
    for (i, line) in lines.iter().enumerate() {
        let e: Edit = serde_json::from_str(line)
            .unwrap_or_else(|err| fail(&format!("chain line {} unreadable: {err}", i + 1)));
        if e.seq != (i + 1) as u64 {
            fail(&format!("chain entry {} claims seq {}", i + 1, e.seq));
        }
        if e.prev != prev {
            fail(&format!(
                "chain broken at entry {}: it stands on {}, the chain's head there is {}",
                e.seq, e.prev, prev
            ));
        }
        let want = sha256_hex(entry_body(&e, legacy).as_bytes());
        if want != e.hash {
            fail(&format!("chain entry {} does not hash to its line", e.seq));
        }
        prev = e.hash.clone();
        edits.push(e);
    }
    edits
}

// The head hash each document currently answers to: only kept
// edits move a document. Proposals and discards are history, not
// state.
fn heads(edits: &[Edit]) -> BTreeMap<String, String> {
    let mut m = BTreeMap::new();
    for e in edits {
        if e.kind == "edit" {
            m.insert(e.doc.clone(), e.after.clone());
        }
    }
    m
}

// Proposals that no keep or discard has resolved yet.
fn pending(edits: &[Edit]) -> Vec<&Edit> {
    let resolved: Vec<u64> = edits
        .iter()
        .filter(|e| e.kind == "edit" || e.kind == "discard")
        .filter_map(|e| e.ref_seq)
        .collect();
    edits
        .iter()
        .filter(|e| e.kind == "propose" && !resolved.contains(&e.seq))
        .collect()
}

fn verified_world(world: &Path) -> (Vec<Edit>, BTreeMap<String, String>) {
    if !world.exists() {
        fail(&format!("no world at {}", world.display()));
    }
    let edits = read_chain(world);
    let want = heads(&edits);
    let mut texts = BTreeMap::new();
    let dir = docs_dir(world);
    if dir.exists() {
        for entry in std::fs::read_dir(&dir).unwrap() {
            let entry = entry.unwrap();
            let name = entry.file_name().to_string_lossy().to_string();
            let bytes = std::fs::read(entry.path()).unwrap();
            match want.get(&name) {
                Some(h) if *h == sha256_hex(&bytes) => {
                    texts.insert(name, String::from_utf8_lossy(&bytes).to_string());
                }
                Some(h) => fail(&format!(
                    "document {name} does not answer to the chain - its head is {}, its bytes hash to {} - it was touched outside the window",
                    short(h),
                    short(&sha256_hex(&bytes))
                )),
                None => fail(&format!(
                    "document {name} exists but no kept edit in the chain ever made it - it was placed outside the window"
                )),
            }
        }
    }
    for name in want.keys() {
        if !texts.contains_key(name) {
            fail(&format!("document {name} is in the chain but missing from docs/"));
        }
    }
    (edits, texts)
}

fn append(world: &Path, kind: &str, doc: &str, before: Option<String>, after: String, ref_seq: Option<u64>) -> Edit {
    let edits = if chain_path(world).exists() {
        read_chain(world)
    } else {
        Vec::new()
    };
    let prev = edits
        .last()
        .map(|e| e.hash.clone())
        .unwrap_or_else(|| "GENESIS".to_string());
    let seq = edits.len() as u64 + 1;
    let mut edit = Edit {
        seq,
        kind: kind.to_string(),
        doc: doc.to_string(),
        before,
        after,
        ref_seq,
        prev,
        hash: String::new(),
    };
    edit.hash = sha256_hex(entry_body(&edit, false).as_bytes());
    let mut chain = std::fs::read_to_string(chain_path(world)).unwrap_or_default();
    if !chain.is_empty() && !chain.ends_with('\n') {
        chain.push('\n');
    }
    chain.push_str(&serde_json::to_string(&edit).unwrap());
    chain.push('\n');
    std::fs::write(chain_path(world), chain).unwrap();
    edit
}

fn apply_edit(world: &Path, doc: &str, new_text: &str, ref_seq: Option<u64>) {
    let doc_path = docs_dir(world).join(doc);
    let before = if doc_path.exists() {
        Some(sha256_hex(&std::fs::read(&doc_path).unwrap()))
    } else {
        None
    };
    let after = sha256_hex(new_text.as_bytes());
    std::fs::create_dir_all(docs_dir(world)).unwrap();
    std::fs::write(&doc_path, new_text).unwrap();
    let e = append(world, "edit", doc, before, after, ref_seq);
    println!(
        "- edit {}: {} {} -> {}",
        e.seq,
        e.doc,
        e.before.as_deref().map(short).unwrap_or_else(|| "new".into()),
        short(&e.after)
    );
}

fn file_proposal(world: &Path, doc: &str, text: &str) -> Edit {
    let edits = read_chain(world);
    let before = heads(&edits).get(doc).cloned();
    let after = sha256_hex(text.as_bytes());
    std::fs::create_dir_all(proposals_dir(world)).unwrap();
    let store = proposals_dir(world).join(&after);
    if !store.exists() {
        std::fs::write(&store, text).unwrap();
    }
    let e = append(world, "propose", doc, before, after, None);
    println!(
        "- proposal {}: {} would become {} - optic keep {} {} to accept it",
        e.seq,
        e.doc,
        short(&e.after),
        world.display(),
        e.seq
    );
    e
}

fn proposal_text(world: &Path, e: &Edit) -> String {
    let path = proposals_dir(world).join(&e.after);
    let bytes = std::fs::read(&path).unwrap_or_else(|_| {
        fail(&format!(
            "proposal {} names text {} but proposals/ does not hold it",
            e.seq, e.after
        ))
    });
    if sha256_hex(&bytes) != e.after {
        fail(&format!(
            "the stored text for proposal {} does not hash to {} - the proposals store was touched outside the window",
            e.seq, e.after
        ));
    }
    String::from_utf8_lossy(&bytes).to_string()
}

fn cmd_seed(world: &Path) {
    if world.exists() {
        fail(&format!("{} already exists", world.display()));
    }
    std::fs::create_dir_all(docs_dir(world)).unwrap();
    let founding = "This is a world of Optic.\n\nIt is made of text, it is viewed and molded through one\nwindow, and every shape it has ever held is in its chain.\nMold it: optic update <world> world.txt, new text on stdin.\n";
    apply_edit(world, "world.txt", founding, None);
    println!("world seeded at {}", world.display());
}

fn cmd_view(world: &Path, only: Option<&str>) {
    let (edits, texts) = verified_world(world);
    match only {
        Some(name) => match texts.get(name) {
            Some(t) => print!("{t}"),
            None => fail(&format!("no document named {name} in this world")),
        },
        None => {
            println!(
                "world: {} documents, {} chain entries, {} standing proposals, chain head {}",
                texts.len(),
                edits.len(),
                pending(&edits).len(),
                edits.last().map(|e| short(&e.hash)).unwrap_or_else(|| "GENESIS".into())
            );
            for (name, text) in &texts {
                println!();
                println!("== {name} ==");
                print!("{text}");
                if !text.ends_with('\n') {
                    println!();
                }
            }
        }
    }
}

fn read_stdin() -> String {
    let mut text = String::new();
    std::io::stdin()
        .read_to_string(&mut text)
        .unwrap_or_else(|e| fail(&format!("cannot read text from stdin: {e}")));
    text
}

fn cmd_update(world: &Path, doc: &str) {
    if !world.exists() {
        fail(&format!("no world at {} - seed one first", world.display()));
    }
    if chain_path(world).exists() {
        let _ = verified_world(world);
    }
    let text = read_stdin();
    apply_edit(world, doc, &text, None);
}

fn cmd_propose(world: &Path, doc: &str) {
    let _ = verified_world(world);
    let text = read_stdin();
    file_proposal(world, doc, &text);
}

fn cmd_mutate(world: &Path, doc: &str) {
    let (_, texts) = verified_world(world);
    let text = texts
        .get(doc)
        .unwrap_or_else(|| fail(&format!("no document named {doc} in this world")));
    let edits = read_chain(world);
    let seed = sha256_hex(
        format!(
            "{}|{}",
            heads(&edits).get(doc).cloned().unwrap_or_default(),
            edits.last().map(|e| e.hash.clone()).unwrap_or_default()
        )
        .as_bytes(),
    );
    let pick = u64::from_str_radix(&seed[..8], 16).unwrap_or(0) % 3;
    let paras: Vec<&str> = text.split("\n\n").collect();
    let (op, mutated) = match pick {
        0 if paras.len() > 1 => {
            let mut p = paras.clone();
            let first = p.remove(0);
            p.push(first);
            ("rotate", p.join("\n\n"))
        }
        1 => {
            let first = text.lines().next().unwrap_or("");
            ("echo", format!("{}{}\n", text, first))
        }
        _ if paras.len() > 1 => ("trim", paras[..paras.len() - 1].join("\n\n") + "\n"),
        _ => {
            let first = text.lines().next().unwrap_or("");
            ("echo", format!("{}{}\n", text, first))
        }
    };
    println!("- the world mutates {doc} by {op}");
    file_proposal(world, doc, &mutated);
}

fn cmd_proposals(world: &Path) {
    let (edits, _) = verified_world(world);
    let open = pending(&edits);
    if open.is_empty() {
        println!("no standing proposals");
    }
    for e in open {
        println!(
            "- proposal {}: {} -> {} (stands on {})",
            e.seq,
            e.doc,
            short(&e.after),
            e.before.as_deref().map(short).unwrap_or_else(|| "new".into())
        );
    }
}

fn find_proposal(world: &Path, seq: u64) -> Edit {
    let (edits, _) = verified_world(world);
    let e = edits
        .iter()
        .find(|e| e.seq == seq)
        .unwrap_or_else(|| fail(&format!("no chain entry {seq} in this world")));
    if e.kind != "propose" {
        fail(&format!("entry {seq} is a {}, not a proposal", e.kind));
    }
    if !pending(&edits).iter().any(|p| p.seq == seq) {
        fail(&format!("proposal {seq} is already resolved"));
    }
    e.clone()
}

fn cmd_keep(world: &Path, seq: u64) {
    let e = find_proposal(world, seq);
    let text = proposal_text(world, &e);
    apply_edit(world, &e.doc, &text, Some(seq));
    println!("- proposal {seq} kept: {} is now {}", e.doc, short(&e.after));
}

fn cmd_discard(world: &Path, seq: u64) {
    let e = find_proposal(world, seq);
    let edits = read_chain(world);
    let head = heads(&edits).get(&e.doc).cloned();
    let d = append(world, "discard", &e.doc, head, e.after.clone(), Some(seq));
    println!(
        "- discard {}: proposal {} for {} refused; the fossil stays in the chain",
        d.seq, seq, e.doc
    );
}

fn cmd_graft(world: &Path, other: &Path) {
    let _ = verified_world(world);
    let (_, their_texts) = verified_world(other);
    let (our_edits, _) = verified_world(world);
    let our_heads = heads(&our_edits);
    let mut offered = 0;
    for (name, text) in &their_texts {
        if our_heads.get(name).map(|h| h == &sha256_hex(text.as_bytes())) == Some(true) {
            println!("- {name}: identical already, nothing offered");
            continue;
        }
        println!("- {name}: the other world offers its state");
        file_proposal(world, name, text);
        offered += 1;
    }
    println!("graft complete: {offered} proposals stand for the owner's word");
}

fn cmd_log(world: &Path) {
    let (edits, _) = verified_world(world);
    for e in &edits {
        let detail = match e.kind.as_str() {
            "propose" => format!("proposes {}", short(&e.after)),
            "discard" => format!(
                "discards proposal {}",
                e.ref_seq.map(|r| r.to_string()).unwrap_or_else(|| "?".into())
            ),
            _ => format!(
                "{} -> {}",
                e.before.as_deref().map(short).unwrap_or_else(|| "new".into()),
                short(&e.after)
            ),
        };
        println!("- {}: {} {} {}", e.seq, e.kind, e.doc, detail);
    }
    println!(
        "chain verified: {} entries, unbroken from GENESIS",
        edits.len()
    );
}

fn cmd_compose(world: &Path) {
    let (edits, texts) = verified_world(world);
    let mut counts: BTreeMap<String, usize> = BTreeMap::new();
    for e in &edits {
        if e.kind == "edit" {
            *counts.entry(e.doc.clone()).or_default() += 1;
        }
    }
    let width = counts.values().max().copied().unwrap_or(0).max(1);
    println!("the world, composed from its chain");
    println!();
    for (name, text) in &texts {
        let n = counts.get(name).copied().unwrap_or(0);
        let bar: String = "-".repeat(((n * 40) / width).max(1));
        println!("{name}  {bar} {n} edits, {} bytes", text.len());
    }
    println!();
    println!(
        "{} entries in the chain, {} standing proposals; every bar above is a count taken from the chain itself.",
        edits.len(),
        pending(&edits).len()
    );
}

fn usage() -> ! {
    eprintln!("usage:");
    eprintln!("  optic seed <world>");
    eprintln!("  optic view <world> [doc]");
    eprintln!("  optic update <world> <doc>     (new text on stdin)");
    eprintln!("  optic propose <world> <doc>    (proposed text on stdin)");
    eprintln!("  optic mutate <world> <doc>");
    eprintln!("  optic proposals <world>");
    eprintln!("  optic keep <world> <seq>");
    eprintln!("  optic discard <world> <seq>");
    eprintln!("  optic graft <world> <other-world>");
    eprintln!("  optic log <world>");
    eprintln!("  optic compose <world>");
    exit(2);
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() < 2 {
        usage();
    }
    let world = PathBuf::from(&args[1]);
    match args[0].as_str() {
        "seed" => cmd_seed(&world),
        "view" => cmd_view(&world, args.get(2).map(|s| s.as_str())),
        "update" => match args.get(2) {
            Some(doc) => cmd_update(&world, doc),
            None => usage(),
        },
        "propose" => match args.get(2) {
            Some(doc) => cmd_propose(&world, doc),
            None => usage(),
        },
        "mutate" => match args.get(2) {
            Some(doc) => cmd_mutate(&world, doc),
            None => usage(),
        },
        "proposals" => cmd_proposals(&world),
        "keep" => match args.get(2).and_then(|s| s.parse().ok()) {
            Some(seq) => cmd_keep(&world, seq),
            None => usage(),
        },
        "discard" => match args.get(2).and_then(|s| s.parse().ok()) {
            Some(seq) => cmd_discard(&world, seq),
            None => usage(),
        },
        "graft" => match args.get(2) {
            Some(other) => cmd_graft(&world, &PathBuf::from(other)),
            None => usage(),
        },
        "log" => cmd_log(&world),
        "compose" => cmd_compose(&world),
        _ => usage(),
    }
}
